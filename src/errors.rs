//! 错误类型定义模块
//! 包含应用程序使用的自定义错误类型

use thiserror::Error;

//==================================================================================================
// 错误类型定义
//==================================================================================================

/// 物理设备适用性检查错误类型
#[derive(Debug, Error)]
pub enum SuitabilityError {
    #[error("静态错误: {0}")]
    Static(&'static str),
    #[error("动态错误: {0}")]
    Dynamic(String),
}
